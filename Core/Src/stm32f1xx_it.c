//定义一个全局变量，用于在中断服务程序中记录按键状态
uint8_t key_state = 0;
void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
  if(GPIO_Pin == KEY1_Pin || GPIO_Pin == KEY2_Pin || GPIO_Pin == KEY3_Pin || GPIO_Pin == KEY4_Pin){
   
    HAL_Delay(4); // 延时消抖
      if(HAL_GPIO_ReadPin(KEY1_GPIO_Port, KEY1_Pin) == GPIO_PIN_RESET) {// 检测按键是否仍然按下
        printf("Key1");
        key_state = 1; // 设置按键1状态
    }else if(HAL_GPIO_ReadPin(KEY2_GPIO_Port, KEY2_Pin) == GPIO_PIN_RESET) {
        printf("Key2");
        key_state = 2; // 设置按键2状态
    }else if(HAL_GPIO_ReadPin(KEY3_GPIO_Port, KEY3_Pin) == GPIO_PIN_RESET) {
        printf("Key3");
        key_state = 3; // 设置按键3状态
    }else if(HAL_GPIO_ReadPin(KEY4_GPIO_Port, KEY4_Pin) == GPIO_PIN_RESET) {
        printf("Key4");
        key_state = 4; // 设置按键4状态
    }
  }
}

